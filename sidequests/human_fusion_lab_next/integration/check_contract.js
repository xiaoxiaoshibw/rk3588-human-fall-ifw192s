'use strict';
// Cross-consumer regression: engine IDs, partial negatives and current support.
const assert = require('assert');
const I = require('../contracts/index_v1');
const E = require('../contracts/strict_v2');
const coordinate = {R: [1,0,0,0,1,0,0,0,1], T: [0,0,1.38], already_leveled: false};
const mapped = I.mapFrame(Float32Array.from([0,0,0,1, 1,0,0,2, 1,0,0,2, NaN,0,0,3]), coordinate);
assert.deepStrictEqual(Array.from(mapped.compact_to_raw), [1,2]);
assert(Number.isNaN(mapped.leveled_xyzi[2]));
assert.deepStrictEqual(I.compactIdsToRaw([1,0], mapped), [2,1]);
assert.notStrictEqual(I.pointsetSha([1]), I.pointsetSha([2]));
const gt = [{id:'person', class_name:'PERSON', raw_indices:[1,2]}];
const candidate = {id:'c', raw_indices:[1,2], decision:'CONFIRMED_HUMAN', track_id:'FUS_t0_7', track_segment:0};
const track = {id:7, track_segment:0, human_confirmed:true, lost:0};
const frame = {gt, candidates:[candidate], raw_components:[candidate], tracks:[track], qualification:'PARTIAL'};
assert.strictEqual(E.evaluateFrame(frame).observed_confirmed.tp, 1);
assert.strictEqual(E.evaluateFrame({...frame, tracks:[{...track,lost:1}]}).observed_confirmed.tp, 0);
assert.strictEqual(E.evaluateFrame({...frame, candidates:[]}).observed_confirmed.fn, 1);
assert.strictEqual(E.evaluateFrame({...frame, candidates:[{...candidate,track_segment:1}]}).observed_confirmed.tp, 0);
assert.deepStrictEqual(E.evaluateFrame({...frame, qualification:'UNKNOWN'}).observed_ids, [7]);
const negative = {id:'furniture',class_name:'FURNITURE',source:'human',raw_indices:[8,9]};
const unknown = {...candidate,id:'u',raw_indices:[8,9],track_id:'FUS_t0_8'};
let result = E.evaluateFrame({...frame,gt:[...gt,negative],candidates:[candidate,unknown]});
assert.strictEqual(result.accepted.fp, 0);
assert.strictEqual(result.accepted.unmatched_unknown, 1);
result = E.evaluateFrame({...frame,gt:[...gt,{...negative,negative_reviewed:true}],candidates:[candidate,unknown]});
assert.strictEqual(result.accepted.fp, 1);
assert.strictEqual(E.evaluateFrame({...frame,candidates:[candidate,{...candidate,id:'dup'}]}).accepted.tp, 1);
assert.strictEqual(E.evaluateFrame({...frame,raw_components:[{...candidate,hard_gate_pass:false}]}).proposal.fn, 1);
assert.throws(()=>E.members({raw_indices:[1,1]}), /duplicate/);
console.log('INTEGRATION_CONTRACT_PASS');
