def run_checks(out):
    commands=[([sys.executable,'-B','-W','error',str(HERE/'test_close_contract.py')],ROOT),
              ([sys.executable,'-B','-W','error','-m','unittest','discover','-s',str(PS),'-p','test_*.py'],ROOT),
              ([sys.executable,'-B','-W','error','-m','unittest','discover','-s','src/human_fall_detection/tests','-p','test_hf06*.py'],ROOT)]
    commands += [(['node',name],ROOT/'pc_apps/human_replay') for name in ['human_pipe_lib.test.js','registration.test.js','human_replay_lib.test.js','panel.test.js']]
    results=[]
    for i,(cmd,cwd) in enumerate(commands):
        r=subprocess.run(cmd,cwd=cwd,capture_output=True,encoding='utf8',errors='replace')
        (out/f'TEST_{i+1:02d}.log').write_text(r.stdout+r.stderr,encoding='utf8')
        results.append({'command':cmd,'cwd':str(cwd),'exit_code':r.returncode,'log':f'TEST_{i+1:02d}.log'})
    dump(out/'TEST_RUNS.json',results)
    if any(r['exit_code'] for r in results):raise RuntimeError('check failed')


