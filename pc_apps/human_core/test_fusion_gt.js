doc.frames_objects['1']=['c'];doc.objects.c={...p(0),class_name:'PERSON',track_id:'P1'};
assert.strictEqual(V.evaluate(trackRun,{eligible:true},doc,meta,.75).adjacent_annotated_id_switches,2);
